const YEARS_DIR = path.join(__dirname, 'data', 'years');
const cardCache = new Map();
function card(year) {
  if (!cardCache.has(year)) {
    cardCache.set(year, JSON.parse(fs.readFileSync(path.join(YEARS_DIR, `${year}.json`), 'utf8')));
  }
  return cardCache.get(year);
}

