/* 总榜要用的两条世界级序列：世界 GDP，和中国当年那种钱兑美元的价。
 *
 * 总榜怎么算（sway 定的口径）：
 *   1. 玩家三十天净赚多少 —— 用他那一年那种钱
 *   2. 按当年的汇率换成当年的美元
 *   3. 除以当年的世界 GDP，再乘以 2025 年的世界 GDP
 * 读出来是：**你捞走的那一块，搁在今天的世界里值多少**。
 * 1930 年赚一千美元，那时候整个世界经济只有今天的二十几分之一，
 * 所以它折到今天是两万多，不是一千。
 *
 * 每年自己还有一个榜（1949 年的人只跟 1949 年的人比），那个榜直接按当年那种钱排，
 * 币制断代在年内根本不构成问题。这两层是 sway 定的，不是我原来那个「几年的收入」。
 * 「几年的收入」留着当榜上的一列给人看。
 */

