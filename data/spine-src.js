/* ── 默认落点城市：那一年最有戏的地方 ────────────────── */
function cityOf(y) {
  if (y <= 1936) return '上海';
  if (y <= 1945) return y >= 1938 ? '重庆' : '武汉';
  if (y <= 1949) return '上海';
  if (y <= 1957) return '天津';
  if (y <= 1965) return '沈阳';
  if (y <= 1976) return '北京';
  if (y <= 1983) return '广州';
  if (y <= 1991) return '深圳';
  if (y <= 1996) return '海口';
  if (y <= 2003) return '上海';
  if (y <= 2012) return '北京';
  return '杭州';
}

/* ── 现实上限：30 天最多能赚到几年的中位收入。
 *
 * 这个数说的是**一个从一成年收入起步、没背景没关系的人**，
 * 三十天里能做到的顶，不是这一行做到顶的那个人能挣多少。
 * 两者差得很远：1940 年重庆的大囤积商一个月确实能过手几万法币，
 * 可他有本钱有路子；揣着一百二十五块法币刚落地的人做不到。
 *
 * 头一版按「这一行的天花板」定，1940 年代给到 50–120 年，
 * 五十局标定跑出来 1940 年 1 月一局 23.4 年，把整个 40 年代拉到全体中位数的 24 倍。
 * 这一版按「白手起家的顶」重定，普遍降到原来的三到四成。
 * ── */
function ceilingOf(y) {
  if (y <= 1936) return 8;      // 上海滩投机、跑单帮，本钱小的做不大
  if (y <= 1945) return 12;     // 战时囤积走私，赚得快也赔得快
  if (y <= 1949) return 20;     // 恶性通胀，黄金美钞黑市，一个月翻几倍是真的
  if (y <= 1952) return 5;
  if (y <= 1955) return 3;
  if (y <= 1965) return 1.2;
  if (y <= 1976) return 0.8;    // 除了工资几乎没有别的进项
  if (y <= 1984) return 3;
  if (y <= 1992) return 8;      // 双轨制、批文、倒爷
  if (y <= 1999) return 12;     // 下海、股市、地产
  if (y <= 2010) return 15;
  if (y <= 2020) return 18;
  return 12;
}

